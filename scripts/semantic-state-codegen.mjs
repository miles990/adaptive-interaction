// Invoked only by aip-codegen.mjs; generated DTOs never become hash inputs.
import { readFileSync } from "node:fs";
import { join } from "node:path";

function fields(schema) {
  if (schema.properties) return schema;
  if (schema.oneOf) {
    const properties = Object.assign({}, ...schema.oneOf.map((branch) => branch.properties ?? {}));
    if (properties.kind) properties.kind = { type: "string" };
    return { properties, required: ["kind"] };
  }
  return null;
}
function type(schema, swift) {
  if (schema.$ref) return `Semantic${schema.$ref.split("/").pop()}Wire`;
  if (schema.type === "string" || schema.const !== undefined) return swift ? "String" : "string";
  if (schema.type === "number" || schema.type === "integer") return swift ? "Double" : "number";
  if (schema.type === "boolean") return swift ? "Bool" : "boolean";
  if (schema.type === "array") return swift ? `[${type(schema.items, true)}]` : `Array<${type(schema.items, false)}>`;
  throw new Error(`unsupported semantic-state codegen shape: ${JSON.stringify(schema)}`);
}
export function semanticFieldPaths(schema) {
  const paths = new Set();
  function visit(node, path) {
    if (node.$ref) return visit(schema.$defs[node.$ref.split("/").pop()], path);
    const object = fields(node);
    if (object) for (const [key, value] of Object.entries(object.properties)) {
      const next = `${path}/${key}`;
      paths.add(next);
      visit(value, next);
    }
    if (node.type === "array") visit(node.items, `${path}/*`);
  }
  visit(schema, "");
  return [...paths].sort();
}
export function semanticArtifacts(root) {
  const schema = JSON.parse(readFileSync(join(root, "schemas/semantic-state-1.0.schema.json"), "utf8"));
  const policy = JSON.parse(readFileSync(join(root, "schemas/semantic-state-consumers.json"), "utf8"));
  const paths = semanticFieldPaths(schema);
  for (const path of paths) for (const consumer of ["typescript", "swift"]) {
    if (!["projected", "retained"].includes(policy.fields[path]?.[consumer])) {
      throw new Error(`semantic consumer handling missing: ${consumer} ${path}; declare projected or retained in schemas/semantic-state-consumers.json`);
    }
  }
  if (Object.keys(policy.fields).some((path) => !paths.includes(path))) throw new Error("semantic consumer policy contains a removed schema field");
  const header = "// GENERATED by scripts/aip-codegen.mjs — do not edit.\n// Source: schemas/semantic-state-1.0.schema.json (interaction-session).\n";
  const ts = [header];
  const swift = [header, "import Foundation", ""];
  const defs = { SemanticState: schema, ...schema.$defs };
  for (const [name, node] of Object.entries(defs)) {
    const object = fields(node);
    const typename = `Semantic${name === "SemanticState" ? "State" : name}Wire`;
    if (!object) {
      ts.push(`export type ${typename} = ${type(node, false)};`, "");
      swift.push(`typealias ${typename} = ${type(node, true)}`, "");
      continue;
    }
    // Open tagged variants retain fields outside their selected branch as raw
    // data. Flattening every variant's fields into one strict DTO would reject
    // future/none variants merely because an opaque `id` is not a String.
    const variants = node.oneOf;
    if (variants) {
      ts.push(`export type ${typename} =`);
      for (const branch of variants) {
        const members = Object.entries(branch.properties).map(([key, child]) =>
          `${key}${(branch.required ?? []).includes(key) ? "" : "?"}: ${child.const === undefined ? type(child, false) : JSON.stringify(child.const)}`);
        ts.push(`  | { ${members.join("; ")}; [key: string]: unknown }`);
      }
      ts.push(";", "");
    } else ts.push(`export interface ${typename} {`);
    swift.push(`struct ${typename}: Codable, Equatable {`);
    for (const [key, node] of Object.entries(object.properties)) {
      const required = (object.required ?? []).includes(key);
      if (!variants) ts.push(`  ${key}${required ? "" : "?"}: ${type(node, false)};`);
      swift.push(`    var ${key}: ${type(node, true)}${required ? "" : "?"}`);
    }
    if (!variants) ts.push("}", "");
    if (variants) {
      const keys = Object.keys(object.properties);
      swift.push(`    private enum CodingKeys: String, CodingKey { case ${keys.join(", ")} }`);
      swift.push("    init(from decoder: Decoder) throws {", "        let c = try decoder.container(keyedBy: CodingKeys.self)", "        kind = try c.decode(String.self, forKey: .kind)");
      for (const key of keys.filter(key => key !== "kind")) swift.push(`        ${key} = nil`);
      swift.push("        switch kind {");
      for (const branch of variants) {
        const discriminator = branch.properties.kind.const;
        if (discriminator === undefined) continue;
        const members = Object.entries(branch.properties).filter(([key]) => key !== "kind");
        if (!members.length) continue;
        swift.push(`        case ${JSON.stringify(discriminator)}:`);
        for (const [key, child] of members) swift.push(`            ${key} = try c.${(branch.required ?? []).includes(key) ? "decode" : "decodeIfPresent"}(${type(child, true)}.self, forKey: .${key})`);
      }
      swift.push("        default: break", "        }", "    }");
    }
    swift.push("}", "");
  }
  ts.push(`export const SEMANTIC_STATE_PROFILE = ${JSON.stringify(schema.profile)};`);
  ts.push(`export const SEMANTIC_STATE_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;`);
  ts.push(`export const SEMANTIC_STATE_CONSUMER_FIELDS = ${JSON.stringify(policy.fields, null, 2)} as const;`, "");
  const json = JSON.stringify(schema);
  if (json.includes('"""#')) throw new Error("semantic schema collides with Swift raw delimiter");
  swift.push("enum SemanticStateContract {", `    static let profile = ${JSON.stringify(schema.profile)}`, `    static let schema = SemanticJSON.parse(#"""\n${json}\n"""#)`, "}", "");
  return [
    [join(root, "apps/interaction-desktop/src/aip/semanticStateGenerated.ts"), ts.join("\n")],
    [join(root, "apps/interaction-ios/InteractionCompanion/Models/SemanticStateGenerated.swift"), swift.join("\n")],
  ];
}
